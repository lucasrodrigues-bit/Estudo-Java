public class Arrays03 {
    static void main(String[] args) {
        String [] nomes = new String [4];
        nomes[0] = "Goku";
        nomes[1] = "Naruto";
        nomes[2] = "luffy";
        nomes[3] = "Sasuke";
        for (int i = 0; i<nomes.length; i++){
            System.out.println(nomes[i]);
        }
    }
}
